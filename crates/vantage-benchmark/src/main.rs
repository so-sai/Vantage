use clap::Parser;
use std::path::PathBuf;
use std::time::SystemTime;
use vantage_benchmark::{
    compare_runs, execute_benchmark, scan_local_repo,
    generate_repo_scenarios, Strategy,
};

#[derive(Parser, Debug)]
#[command(name = "vantage-benchmark")]
#[command(version = "1.2.5")]
#[command(about = "Vantage Reality Benchmark Harness", long_about = None)]
struct Args {
    /// Path to the repository to scan and benchmark.
    #[arg(long, default_value = ".")]
    repo_path: PathBuf,
}

fn main() {
    let args = Args::parse();

    println!("Starting Vantage Reality Benchmark...");
    println!("Scanning target path: {}", args.repo_path.display());

    let scan = match scan_local_repo(&args.repo_path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("Error scanning repository: {}", e);
            std::process::exit(1);
        }
    };

    if scan.primary_files.is_empty() {
        eprintln!("Error: No primary source files (.rs, .ts, .tsx, .py, .js) found in target path.");
        std::process::exit(1);
    }

    let total_primary_tokens: u64 = scan.primary_files.iter().map(|(_, t)| t).sum();
    let total_secondary_tokens: u64 = scan.secondary_files.iter().map(|(_, t)| t).sum();

    let scenarios = generate_repo_scenarios(&scan);

    // Render report
    println!("\n# Vantage Reality Benchmark Report");
    println!("**Generated At**: {:?}", SystemTime::now());
    println!("**Target Repository**: {}", args.repo_path.display());
    println!("\n## 📊 Repository Scan Summary");
    println!("- **Primary Source Files** (`.rs`, `.ts`, `.tsx`, `.py`, `.js`):");
    println!("  - Count: {} files", scan.primary_files.len());
    println!("  - Total Volume: {} tokens (estimated)", total_primary_tokens);
    println!("- **Secondary Configuration & Docs Files** (`.md`, `.yaml`, `.yml`, `.toml`):");
    println!("  - Count: {} files", scan.secondary_files.len());
    println!("  - Total Volume: {} tokens (estimated)", total_secondary_tokens);

    println!("\n---");

    println!("\n## ⚙️ Scenario Benchmarks (Level 1 - Local Repo)");
    println!("For each development scenario, we measure Vantage's savings against the standard inference-only baseline:\n");
    println!("| Scenario | Strategy | Total Inferences | Tokens Processed | State Cache Reads | Reality Commits |");
    println!("| :--- | :--- | :--- | :--- | :--- | :--- |");

    let mut feature_iar = 0.0;
    let mut bug_iar = 0.0;
    let mut refactor_iar = 0.0;
    let mut feature_rrf = 1.0;
    let mut bug_rrf = 1.0;
    let mut refactor_rrf = 1.0;

    for (name, ops) in &scenarios {
        let baseline = execute_benchmark(ops, Strategy::InferenceOnly);
        let vantage = execute_benchmark(ops, Strategy::StateCached);
        let cmp = compare_runs(&baseline, &vantage);

        if name == "Feature Addition" {
            feature_iar = cmp.iar;
            feature_rrf = cmp.rrf;
        } else if name == "Bug Fix" {
            bug_iar = cmp.iar;
            bug_rrf = cmp.rrf;
        } else if name == "Core Refactoring" {
            refactor_iar = cmp.iar;
            refactor_rrf = cmp.rrf;
        }

        println!(
            "| **{}** | InferenceOnly (Baseline) | {} | {} | 0 | 0 |",
            name, baseline.total_inferences, baseline.total_tokens
        );
        println!(
            "| | StateCached (Vantage) | {} | {} | {} | {} |",
            vantage.total_inferences, vantage.total_tokens, vantage.state_reads, vantage.reality_commits
        );
    }

    println!("\n### 📈 Efficiency Summary");
    println!("- **Inference Avoidance Ratio (IAR)**:");
    println!("  - Feature Addition: **{:.1}%** (avoided inference passes)", feature_iar * 100.0);
    println!("  - Bug Fix: **{:.1}%**", bug_iar * 100.0);
    println!("  - Core Refactoring: **{:.1}%**", refactor_iar * 100.0);
    println!("- **Reality Reuse Factor (RRF)**:");
    println!("  - Feature Addition: **{:.2}x** (reads per committed reality)", feature_rrf);
    println!("  - Bug Fix: **{:.2}x**", bug_rrf);
    println!("  - Core Refactoring: **{:.2}x**", refactor_rrf);

    println!("\n---");
    println!("*Generated by Vantage Benchmark Harness v1.2.5*");
}
